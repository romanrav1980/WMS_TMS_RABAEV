SELECT
  DECODE(N,1000000,NULL,N) N,
  схд,
  DECODE(N,щйяоедхрнп,NULL,щйяоедхрнп) бндхрекэ,
  яейрнп,
  мнлеп,
  тн н,
  чп_кхжн,
  йкхемр,
  DECODE(ясллю,0,NULL,DECODE( 'пСАКЭ' ,4,TO_CHAR(ясллю,'9999999999.00'),3,TO_CHAR(ясллю,'$9999999999.00'))) ясллю,
  DECODE(ROUND(бея,1),0,NULL,TO_CHAR(бея,'9999999999.0')) бея,
  DECODE(ROUND(назел,1),0,NULL,TO_CHAR(назел,'9999999999.0')) назел,
  юдпея,
  опхлевюмхе||'  '||ро опхлевюмхе,
  бюфмнярэ,
  ондохяэ,
  ROUND(нанпнр-ясллю,0) " "
FROM
  (SELECT * FROM (
  
  SELECT
--    *
 N,
 TRIM(TO_CHAR(схд,'9999999999')) схд,
    щйяоедхрнп,
    яейрнп,
    мнлеп,
    тн,
    чп_кхжн,
    йкхемр,
    ясллю,
    бея,
    назел,
    юдпея,
    опхлевюмхе,
    бюфмнярэ,
    ондохяэ,
    нанпнр,
    ро
    
  FROM
  (
  SELECT ROW_NUMBER() OVER
    (
    PARTITION BY щйяоедхрнп ORDER BY
      щйяоедхрнп,
      юдпея,
      чп_кхжн,
      мнлеп,
      яейрнп,
      йкхемр,
      бюфмнярэ,
      тн
