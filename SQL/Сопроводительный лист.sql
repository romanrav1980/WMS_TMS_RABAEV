    щйяоедхрнп,
    яейрнп,
    мнлеп,
    тн,
    чп_кхжн,
    йкхемр,
    ясллю,
    бея,
    назел,
    юдпея,
    опхлевюмхе,
    бюфмнярэ,
    ондохяэ,
    нанпнр,
    схд,
    ро
  FROM
    (
    SELECT
      м.схд схд,
      щ.юаапебхюрспю щйяоедхрнп,
      я.мюхлемнбюмхе яейрнп,
