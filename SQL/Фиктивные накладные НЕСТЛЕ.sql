SELECT   М.Наименование , П.ТМЦ_УИД , sum( П.КОЛ_ВО_ПАЧЕК ) kol , max( П.ЦЕНА ) cena  
   FROM R.ПОЗИЦИИ_ТМЦ П, R.НАКЛАДНЫЕ Н, R.ДОКУМЕНТЫ Д , R.МАТЕРИАЛЫ М 
   WHERE     П.НАКЛ_УИД = Н.УИД 
    AND Н.ДОК_УИД = Д.УИД 
    AND Д.ВИД = 1 
    and П.ТМЦ_УИД=М.УИД 
    AND Д.ТИП IN (1, 2) 
    and Дата_Закрытия > to_date( '220909' , 'ddmmyy' ) and 
    Номер in ( 'ЕК80000' , 'ЕК79993' , 'ЕК79990' , 'ЕК79989' , 'ЕК79988' )

group by П.ТМЦ_УИД , М.Наименование




