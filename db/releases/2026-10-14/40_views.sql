  CREATE OR REPLACE FORCE EDITIONABLE VIEW "RABAEV"."RRL_PROD_BATCH_READY_V" ("PROD_BATCH_ID", "PROD_BATCH_NO", "PRODUCTION_ORDER_ID", "ARTICUL", "WARE_ID", "QUALITY_STATUS", "AGING_REQUIRED_HOURS", "AGING_UNTIL", "SHIPMENT_ALLOWED_AT", "SHIPMENT_RELEASE_STATUS", "SHIPMENT_BLOCK_REASON", "SHIPMENT_EFFECTIVE_STATUS", "IS_SHIPMENT_ALLOWED", "CREATED_AT", "UPDATED_AT") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  select b.PROD_BATCH_ID,
       b.PROD_BATCH_NO,
       b.PRODUCTION_ORDER_ID,
       b.ARTICUL,
       b.WARE_ID,
       b.QUALITY_STATUS,
       b.AGING_REQUIRED_HOURS,
       b.AGING_UNTIL,
       b.SHIPMENT_ALLOWED_AT,
       b.SHIPMENT_RELEASE_STATUS,
       b.SHIPMENT_BLOCK_REASON,
       case
         when nvl(b.QUALITY_STATUS, 'DRAFT') in ('DRAFT', 'BLOCKED', 'QUALITY_HOLD', 'LAB_PENDING', 'REJECTED') then 'BLOCKED'
         when b.SHIPMENT_RELEASE_STATUS in ('BLOCKED', 'QUALITY_HOLD', 'REJECTED') then 'BLOCKED'
         when b.SHIPMENT_ALLOWED_AT is not null and b.SHIPMENT_ALLOWED_AT > sysdate then 'WAIT_AGING'
         else 'READY'
       end SHIPMENT_EFFECTIVE_STATUS,
       case
         when nvl(b.QUALITY_STATUS, 'DRAFT') in ('DRAFT', 'BLOCKED', 'QUALITY_HOLD', 'LAB_PENDING', 'REJECTED') then 0
         when b.SHIPMENT_RELEASE_STATUS in ('BLOCKED', 'QUALITY_HOLD', 'REJECTED') then 0
         when b.SHIPMENT_ALLOWED_AT is not null and b.SHIPMENT_ALLOWED_AT > sysdate then 0
         else 1
       end IS_SHIPMENT_ALLOWED,
       b.CREATED_AT,
       b.UPDATED_AT
  from RRL_PROD_BATCH b;


  CREATE OR REPLACE FORCE EDITIONABLE VIEW "RABAEV"."RRL_TARE_AVAILABILITY" ("BALANCE_KEY", "OWNER_WARE_ID", "PALLET_TYPE_ID", "CUSTODIAN_ID", "PHYSICAL_QTY", "BALANCE_VERSION", "ASSEMBLY_QTY", "AVAILABLE_QTY", "LOSS_PENDING_QTY") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  select b.BALANCE_KEY,b.OWNER_WARE_ID,b.PALLET_TYPE_ID,b.CUSTODIAN_ID,b.QUANTITY PHYSICAL_QTY,b.BALANCE_VERSION,
 nvl(h.QTY,0) ASSEMBLY_QTY,b.QUANTITY-nvl(h.QTY,0)-nvl(l.QUANTITY,0) AVAILABLE_QTY,nvl(l.QUANTITY,0) LOSS_PENDING_QTY
from RRL_TARE_BALANCE b left join(select BALANCE_KEY,sum(QUANTITY) QTY from RRL_TARE_BOOK where STATUS='HELD' group by BALANCE_KEY)h on h.BALANCE_KEY=b.BALANCE_KEY
left join RRL_TARE_LOSS_PENDING l on l.BALANCE_KEY=b.BALANCE_KEY
where b.CUSTODIAN_KIND='WAREHOUSE' and b.CONDITION_CODE='GOOD';


  CREATE OR REPLACE FORCE EDITIONABLE VIEW "RABAEV"."RRL_TARE_LOSS_PENDING" ("BALANCE_KEY", "QUANTITY") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  select c.BALANCE_KEY,sum(c.QUANTITY) QUANTITY from RRL_TARE_LOSS_CLAIM c
where not exists(select 1 from RRL_TARE_LOSS_DECISION d where d.CLAIM_OPERATION_ID=c.OPERATION_ID) group by c.BALANCE_KEY;


  CREATE OR REPLACE FORCE EDITIONABLE VIEW "RABAEV"."RRL_TARE_STORE_DEBT" ("OWNER_WARE_ID", "PALLET_TYPE_ID", "CONDITION_CODE", "STORE_ADDR", "TT_ID", "ACCEPT_OPERATION_ID", "CLAIM_KEY", "ACCEPTED_QTY", "LOAN_QTY", "ACCEPTED_AT", "OUTSTANDING_QTY", "SCOPE_KIND", "SCOPE_KEY", "POLICY_VERSION", "RETURN_MODE", "RETURN_DAYS", "TIMEZONE_REGION", "EFFECTIVE_DUE_AT", "DEBT_STATE") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  with damage_totals as(
 select DELIVERY_ACCEPT_OPERATION_ID,sum(QUANTITY) QTY from RRL_TARE_RESOLUTION where RESOLUTION_KIND='DAMAGE' and CUSTODIAN_KIND='STORE' group by DELIVERY_ACCEPT_OPERATION_ID
),writeoff_totals as(
 select DAMAGE_OPERATION_ID,sum(QUANTITY) QTY from RRL_TARE_RESOLUTION where RESOLUTION_KIND='WRITE_OFF' and CUSTODIAN_KIND='STORE' group by DAMAGE_OPERATION_ID
),loss_totals as(
 select c.SOURCE_CLAIM_ID,sum(c.QUANTITY) QTY from RRL_TARE_LOSS_CLAIM c join RRL_TARE_LOSS_DECISION d on d.CLAIM_OPERATION_ID=c.OPERATION_ID and d.OUTCOME='WRITE_OFF'
 where c.SOURCE_CLAIM_ID is not null group by c.SOURCE_CLAIM_ID
),loans as(
 select o.OWNER_WARE_ID,o.PALLET_TYPE_ID,o.CONDITION_CODE,o.TO_ID STORE_ADDR,o.TT_ID,a.OPERATION_ID ACCEPT_OPERATION_ID,a.OPERATION_ID CLAIM_KEY,
 a.ACCEPTED_QTY ORIGINAL_ACCEPTED_QTY,a.ACCEPTED_QTY-nvl(dt.QTY,0)-nvl(lt.QTY,0) LOAN_QTY,a.ACCEPTED_AT,a.ACCEPTED_AT CLAIM_CREATED_AT
 from RRL_TARE_OFFER o join RRL_TARE_ACCEPT a on a.OFFER_OPERATION_ID=o.OPERATION_ID left join damage_totals dt on dt.DELIVERY_ACCEPT_OPERATION_ID=a.OPERATION_ID left join loss_totals lt on lt.SOURCE_CLAIM_ID=a.OPERATION_ID where o.TO_KIND='STORE'
 union all
 select r.OWNER_WARE_ID,r.PALLET_TYPE_ID,'DAMAGED',r.CUSTODIAN_ID,o.TT_ID,a.OPERATION_ID,r.OPERATION_ID,
 r.QUANTITY,r.QUANTITY-nvl(wt.QTY,0)-nvl(lt.QTY,0),a.ACCEPTED_AT,r.CREATED_AT
 from RRL_TARE_RESOLUTION r join RRL_TARE_ACCEPT a on a.OPERATION_ID=r.DELIVERY_ACCEPT_OPERATION_ID
 join RRL_TARE_OFFER o on o.OPERATION_ID=a.OFFER_OPERATION_ID left join writeoff_totals wt on wt.DAMAGE_OPERATION_ID=r.OPERATION_ID left join loss_totals lt on lt.SOURCE_CLAIM_ID=r.OPERATION_ID
 where r.RESOLUTION_KIND='DAMAGE' and r.CUSTODIAN_KIND='STORE'
),delivered as(
 select l.*,nvl(sum(LOAN_QTY) over(partition by OWNER_WARE_ID,PALLET_TYPE_ID,CONDITION_CODE,STORE_ADDR order by ACCEPTED_AT,CLAIM_CREATED_AT,CLAIM_KEY rows between unbounded preceding and 1 preceding),0) PREVIOUS_DELIVERED from loans l
),returned as(
 select o.OWNER_WARE_ID,o.PALLET_TYPE_ID,o.CONDITION_CODE,o.FROM_ID STORE_ADDR,sum(a.ACCEPTED_QTY) RETURNED_QTY
 from RRL_TARE_OFFER o join RRL_TARE_ACCEPT a on a.OFFER_OPERATION_ID=o.OPERATION_ID where o.FROM_KIND='STORE'
 group by o.OWNER_WARE_ID,o.PALLET_TYPE_ID,o.CONDITION_CODE,o.FROM_ID
),facts as(
 select d.OWNER_WARE_ID,d.PALLET_TYPE_ID,d.CONDITION_CODE,d.STORE_ADDR,d.TT_ID,d.ACCEPT_OPERATION_ID,d.CLAIM_KEY,d.ORIGINAL_ACCEPTED_QTY ACCEPTED_QTY,d.LOAN_QTY,d.ACCEPTED_AT,
 greatest(0,d.LOAN_QTY-greatest(0,nvl(r.RETURNED_QTY,0)-d.PREVIOUS_DELIVERED)) OUTSTANDING_QTY,
 p.SCOPE_KIND,p.SCOPE_KEY,p.POLICY_VERSION,p.RETURN_MODE,p.RETURN_DAYS,p.TIMEZONE_REGION,
 case when p.RETURN_MODE='NEXT_DELIVERY' then(
 select min(sr.RECEIVED_AT) from RRL_STORE_RECEIPT_FACT sr join RRL_TT_HU_LOAD_FACT lf on lf.LOAD_OPERATION_ID=sr.LOAD_OPERATION_ID
 where sr.STORE_ADDR=d.STORE_ADDR and sr.RECEIVED_AT>d.ACCEPTED_AT and lf.TT_ID!=d.TT_ID
 )else p.DUE_AT end EFFECTIVE_DUE_AT
 from delivered d left join returned r on r.OWNER_WARE_ID=d.OWNER_WARE_ID and r.PALLET_TYPE_ID=d.PALLET_TYPE_ID and r.CONDITION_CODE=d.CONDITION_CODE and r.STORE_ADDR=d.STORE_ADDR
 left join RRL_TARE_DELIVERY_POLICY p on p.ACCEPT_OPERATION_ID=d.ACCEPT_OPERATION_ID
)
select f."OWNER_WARE_ID",f."PALLET_TYPE_ID",f."CONDITION_CODE",f."STORE_ADDR",f."TT_ID",f."ACCEPT_OPERATION_ID",f."CLAIM_KEY",f."ACCEPTED_QTY",f."LOAN_QTY",f."ACCEPTED_AT",f."OUTSTANDING_QTY",f."SCOPE_KIND",f."SCOPE_KEY",f."POLICY_VERSION",f."RETURN_MODE",f."RETURN_DAYS",f."TIMEZONE_REGION",f."EFFECTIVE_DUE_AT",case when OUTSTANDING_QTY=0 then 'SETTLED' when POLICY_VERSION is null then 'UNCONFIGURED_LEGACY'
 when RETURN_MODE='NEXT_DELIVERY' and EFFECTIVE_DUE_AT is null then 'WAITING_NEXT_DELIVERY'
 when EFFECTIVE_DUE_AT<=systimestamp then 'OVERDUE' else 'OPEN' end DEBT_STATE from facts f;


  CREATE OR REPLACE FORCE EDITIONABLE VIEW "RABAEV"."RRL_TRP_REGIONS" ("REGION", "ORD") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  select region, min(ord) ord
  from RRL_ADDR
 where region is not null
 group by region;


  CREATE OR REPLACE FORCE EDITIONABLE VIEW "RABAEV"."RRL_V_AVAILABLE_STS" ("ST_NUMBER", "ADDR", "REGION", "RAION", "ORD", "SHIROTA", "DOLGOTA", "TRANSPORT_TYPE", "NEEDS_HYDRO_BOARD", "STOL", "PRIM1", "WARE_ID", "NAPR", "PALLETS_COUNT", "WEIGHT_KG", "VOLUME_M3", "STDATE", "DATE_LOAD", "TRANSTASK_ID", "VERIFY_PERC", "SUGAR", "MAX_VEHICLE_TONS", "TW_STRICT", "UNLOAD_NORM_MIN") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT
  P.ST_NUMBER,
  P.ADDR,
  NVL(A.REGION, P.ADDR)                                        AS REGION,
  A.RAION,
  A.ORD,
  A.SHIROTA,
  A.DOLGOTA,
  NVL(A.TRANSPORT_TYPE, '0')                                    AS TRANSPORT_TYPE,
  NVL(A.STOL, 0)                                                AS NEEDS_HYDRO_BOARD,
  NVL(A.STOL, 0)                                                AS STOL,
  A.PRIM1,
  P.WARE_ID,
  MAX(P.NAPR)                                                   AS NAPR,
  COUNT(DISTINCT P.PALLET_UID)                                  AS PALLETS_COUNT,
  ROUND(SUM(NVL(R.ORDER_WEIGHT, 0)), 0)                         AS WEIGHT_KG,
  ROUND(SUM(NVL(R.TARESIZE, 0) * NVL(R.PACK_COUNT, 0))
        / 1000000, 2)                                           AS VOLUME_M3,
  MIN(P.STDATE)                                                 AS STDATE,
  MIN(P.STDATE)                                                 AS DATE_LOAD,
  MAX(P.TRANSTASK_ID)                                           AS TRANSTASK_ID,
  MAX(RABAEV.RRL_ST_VERYFY_PERC(P.ST_NUMBER))                  AS VERIFY_PERC,
  NVL(MAX(RABAEV.RRL_SUGAR_HAS(R.ARTICUL)), 0)                  AS SUGAR,
  NVL(A.MAX_VEHICLE_TONS, 20)                                   AS MAX_VEHICLE_TONS,
  NVL(A.TW_STRICT, 0)                                          AS TW_STRICT,
  NVL(A.UNLOAD_NORM_MIN, 30)                                    AS UNLOAD_NORM_MIN
FROM RABAEV.RRL_SBORKA_PALLETS P
JOIN RABAEV.RRL_SBORKA_PALLET_ROWS R ON R.PALLET_UID = P.PALLET_UID
LEFT JOIN RABAEV.RRL_ADDR A ON A.ADDR = P.ADDR
WHERE P.CONDITION <> 2
GROUP BY
  P.ST_NUMBER, P.ADDR, A.REGION, A.RAION, A.ORD,
  A.SHIROTA, A.DOLGOTA, P.WARE_ID,
  A.TRANSPORT_TYPE, A.STOL, A.PRIM1,
  A.MAX_VEHICLE_TONS, A.TW_STRICT, A.UNLOAD_NORM_MIN;


