select p.OPERATION_ID,p.SOURCE_LOAD_OPERATION_ID,p.SOURCE_ST_ID,p.SOURCE_TT_ID,p.SOURCE_WARE_ID,
 p.TARGET_WARE_ID,coalesce(d.TARGET_TT_ID,p.TARGET_TT_ID) TARGET_TT_ID,p.ROOT_UID PALLET_IDENTIFIER,p.INBOUND_DOCK,coalesce(d.OUTBOUND_DOCK,p.OUTBOUND_DOCK) OUTBOUND_DOCK,
 to_char(p.ARRIVAL_DUE,'YYYY-MM-DD"T"HH24:MI:SS.FF6TZH:TZM') ARRIVAL_DUE,
 to_char(coalesce(d.READY_DUE,p.READY_DUE),'YYYY-MM-DD"T"HH24:MI:SS.FF6TZH:TZM') READY_DUE,p.DECISION_REFERENCE,p.ACTOR,
 p.TARGET_TT_ID ORIGINAL_TARGET_TRIP_ID,to_char(p.READY_DUE,'YYYY-MM-DD"T"HH24:MI:SS.FF6TZH:TZM') ORIGINAL_READY_DUE,
 coalesce(d.REVISION_NO,0) DECISION_REVISION,d.DECISION_KIND,
 to_char(d.EXPECTED_ARRIVAL,'YYYY-MM-DD"T"HH24:MI:SS.FF6TZH:TZM') EXPECTED_ARRIVAL,d.DECISION_REFERENCE LATEST_DECISION_REFERENCE,
 json_value(p.SOURCE_COMPOSITION_JSON,'$.nodes[0].article') ARTICLE,
 json_value(p.SOURCE_COMPOSITION_JSON,'$.nodes[0].quantity') QUANTITY,
 json_value(p.SOURCE_COMPOSITION_JSON,'$.nodes[0].base_uom') BASE_UOM,
 t.TRANSPORT VEHICLE_NUMBER,u.OPERATION_ID UNLOAD_OPERATION_ID,r.OPERATION_ID RECEIPT_OPERATION_ID,
 f.TASK_ID PLACED_TASK_ID,c.OPERATION_ID CUSTODY_RELEASE_OPERATION_ID,b.ST_IDENTIFIER ONWARD_ST_IDENTIFIER,
 to_char(u.CREATED_AT,'YYYY-MM-DD"T"HH24:MI:SS.FF6TZH:TZM') UNLOADED_AT,
 to_char(r.CREATED_AT,'YYYY-MM-DD"T"HH24:MI:SS.FF6TZH:TZM') RECEIVED_AT,
 to_char(f.CREATED_AT,'YYYY-MM-DD"T"HH24:MI:SS.FF6TZH:TZM') PLACED_AT,
 to_char(systimestamp,'YYYY-MM-DD"T"HH24:MI:SS.FF6TZH:TZM') OBSERVED_AT
from RRL_INTERWARE_PLAN p
left join RRL_INTERWARE_DECISION d on d.PLAN_OPERATION_ID=p.OPERATION_ID and d.REVISION_NO=(select max(z.REVISION_NO)from RRL_INTERWARE_DECISION z where z.PLAN_OPERATION_ID=p.OPERATION_ID)
join RRL_TRANSPORT_TASK t on t.ID=p.SOURCE_TT_ID
left join RRL_INTERWARE_UNLOAD u on u.PLAN_OPERATION_ID=p.OPERATION_ID
left join RRL_INTERWARE_RECEIPT r on r.PLAN_OPERATION_ID=p.OPERATION_ID
left join RRL_INTERWARE_PLACEMENT f on f.RECEIPT_OPERATION_ID=r.OPERATION_ID
left join RRL_INTERWARE_CUSTODY_PROOF c on c.RECEIPT_OPERATION_ID=r.OPERATION_ID
left join RRL_INTERWARE_ONWARD_BIND b on b.RECEIPT_OPERATION_ID=r.OPERATION_ID
where (p.SOURCE_WARE_ID=:ware or p.TARGET_WARE_ID=:ware)
 and (:history=1 or not exists(
  select 1 from RRL_TT_HU_LOAD_ST member_record join RRL_TT_HU_LOAD_FACT load_record on load_record.LOAD_OPERATION_ID=member_record.LOAD_OPERATION_ID
  where member_record.SBORKA_PALLET_ID=b.ST_ID and member_record.ACTIVE_FLAG=1 and load_record.STATUS='DEPARTED'
 ))
order by case when :history=1 then p.ARRIVAL_DUE end desc,p.ARRIVAL_DUE,p.OPERATION_ID fetch first 100 rows only
