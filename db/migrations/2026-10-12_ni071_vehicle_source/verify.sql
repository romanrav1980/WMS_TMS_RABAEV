select OBJECT_NAME,OBJECT_TYPE,STATUS from USER_OBJECTS where OBJECT_NAME in(
'RRL_VEHICLE_PROFILE_API','RRL_VEH_DEPART_SOURCE','RRL_STOCK_TRIP_DEPART_CMD',
'RRL_VEH_PROFILE_HEAD_GUARD','RRL_VEH_PROFILE_HIST_GUARD','RRL_TT_VEH_SOURCE_GUARD');
select s.TT_ID,s.SOURCE_STATE,count(l.LOAD_OPERATION_ID) LOADS,
sum(case when l.DEPARTED_AT=s.CAPTURED_AT then 1 else 0 end) SAME_CLOCK
from RRL_TT_VEHICLE_SOURCE s join RRL_TT_HU_LOAD_FACT l on l.TT_ID=s.TT_ID and l.DEPARTURE_OPERATION_ID=s.DEPARTURE_OPERATION_ID
group by s.TT_ID,s.SOURCE_STATE;
