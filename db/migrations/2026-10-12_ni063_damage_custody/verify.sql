select OBJECT_NAME,OBJECT_TYPE,STATUS from USER_OBJECTS where OBJECT_NAME in(
'RRL_TARE_DAMAGE_TRACE','RRL_STOCK_TARE_CMD','RRL_STOCK_TARE_RESOLVE','RRL_STOCK_TARE_LOSS',
'RRL_TARE_DORIGIN_GUARD','RRL_TARE_DPOSITION_GUARD','RRL_TARE_DOFFER_GUARD','RRL_TARE_DMOVE_GUARD');
select o.DAMAGE_OPERATION_ID,o.QUANTITY,
(select nvl(sum(p.QUANTITY),0)from RRL_TARE_DAMAGE_POSITION p where p.DAMAGE_OPERATION_ID=o.DAMAGE_OPERATION_ID) CURRENT_POSITION,
(select nvl(sum(r.QUANTITY),0)from RRL_TARE_RESOLUTION r where r.DAMAGE_OPERATION_ID=o.DAMAGE_OPERATION_ID and r.RESOLUTION_KIND='WRITE_OFF') WRITTEN_OFF
from RRL_TARE_DAMAGE_ORIGIN o where o.QUANTITY!=
(select nvl(sum(p.QUANTITY),0)from RRL_TARE_DAMAGE_POSITION p where p.DAMAGE_OPERATION_ID=o.DAMAGE_OPERATION_ID)+
(select nvl(sum(r.QUANTITY),0)from RRL_TARE_RESOLUTION r where r.DAMAGE_OPERATION_ID=o.DAMAGE_OPERATION_ID and r.RESOLUTION_KIND='WRITE_OFF');
