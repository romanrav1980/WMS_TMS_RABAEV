      d.PALLETS = s.PALLETS, d.GIDROBORT = s.GIDROBORT, d.REF_REJIM = s.REF_REJIM, d.BLOCKED = 0
    WHEN NOT MATCHED THEN INSERT (
      ID, NUM, TR_TYPE, MARKA, PALLETS, GIDROBORT, REF_REJIM, BLOCKED
    ) VALUES (
      s.ID, s.NUM, s.TR_TYPE, s.MARKA, s.PALLETS, s.GIDROBORT, s.REF_REJIM, 0
    );
  END;

  PROCEDURE upsert_driver(d_rec t_drv) IS
  BEGIN
    MERGE INTO RRL_TR_VODITEL d
    USING (SELECT d_rec.id ID, d_rec.f F, d_rec.i I, d_rec.o O,
                  d_rec.tel TEL, d_rec.own OWN, d_rec.tk_name TK FROM dual) s
    ON (d.ID = s.ID)
    WHEN MATCHED THEN UPDATE SET
      d.F = s.F, d.I = s.I, d.O = s.O, d.TEL = s.TEL,
      d.SOBSTVENNYY = s.OWN, d.DOVERENNOST_OT = s.TK, d.DELETED = 0
    WHEN NOT MATCHED THEN INSERT (
      ID, F, I, O, TEL, TRANSPORT_NUM, SOBSTVENNYY, DOVERENNOST_OT, DELETED
    ) VALUES (
      s.ID, s.F, s.I, s.O, s.TEL, NULL, s.OWN, s.TK, 0
    );
  END;

BEGIN
  -- ──────────────────────────────────────────────────────────────────────────
  -- 1. ОЧИСТКА предыдущего запуска (по маске UID)
  -- ──────────────────────────────────────────────────────────────────────────
  DELETE FROM RRL_SBORKA_PALLET_ROWS
   WHERE PALLET_UID LIKE 'ДЦПЛ%';

  DELETE FROM RRL_SBORKA_PALLETS
   WHERE PALLET_UID LIKE 'ДЦПЛ%';

  -- ──────────────────────────────────────────────────────────────────────────
  -- 2. АДРЕСА МАГАЗИНОВ
  -- ──────────────────────────────────────────────────────────────────────────
  FOR i IN 1..v_addrs.COUNT LOOP
    MERGE INTO RRL_ADDR d
    USING (
      SELECT v_addrs(i).addr        ADDR,
             v_addrs(i).region      REGION,
             v_addrs(i).raion       RAION,
             i                      ORD,
             v_addrs(i).transport_t TRANSPORT_TYPE,
             v_addrs(i).stol        STOL,
             v_addrs(i).lat         SHIROTA,
             v_addrs(i).lon         DOLGOTA
        FROM dual
    ) s ON (d.ADDR = s.ADDR)
    WHEN MATCHED THEN UPDATE SET
      d.REGION         = s.REGION,
      d.RAION          = s.RAION,
      d.ORD            = s.ORD,
      d.TRANSPORT_TYPE = s.TRANSPORT_TYPE,
      d.STOL           = s.STOL,
      d.SHIROTA        = s.SHIROTA,
      d.DOLGOTA        = s.DOLGOTA
    WHEN NOT MATCHED THEN INSERT (
      ADDR, REGION, RAION, ORD, TRANSPORT_TYPE, STOL, SHIROTA, DOLGOTA
    ) VALUES (
      s.ADDR, s.REGION, s.RAION, s.ORD, s.TRANSPORT_TYPE, s.STOL, s.SHIROTA, s.DOLGOTA
    );
  END LOOP;

  -- ──────────────────────────────────────────────────────────────────────────
  -- 3. ТРАНСПОРТНЫЕ СРЕДСТВА
  -- ──────────────────────────────────────────────────────────────────────────
  FOR i IN 1..v_vehs.COUNT LOOP
    upsert_vehicle(v_vehs(i));
  END LOOP;

  -- ──────────────────────────────────────────────────────────────────────────
  -- 4. ВОДИТЕЛИ
  -- ──────────────────────────────────────────────────────────────────────────
  FOR i IN 1..v_drvs.COUNT LOOP
    upsert_driver(v_drvs(i));
  END LOOP;

  -- ──────────────────────────────────────────────────────────────────────────
  -- 5. СБОРОЧНЫЕ ЗАДАНИЯ (СТ) — паллеты + строки
  --
  --   Для каждого адреса создаётся 4–6 СТ (дата отгрузки: завтра или послезавтра).
  --   Каждое СТ: 3–6 паллет. Каждая паллета: 8–12 строк.
  --   TRANSTASK_ID = NULL → готово для диспетчеризации.
  --
  --   ST_NUMBER  : 'ДЦСТ-{WARE_PREFIX}{SEQ6}'
  --   PALLET_UID : 'ДЦПЛ{SEQ8}'
  -- ──────────────────────────────────────────────────────────────────────────
  FOR i IN 1..v_addrs.COUNT LOOP
    v_addr_str := v_addrs(i).addr;
    v_raion    := v_addrs(i).raion;
    v_ware_id  := v_addrs(i).ware_id;

    -- 5 СТ на адрес
    FOR st_idx IN 1..5 LOOP
      v_st_counter := v_st_counter + 1;

      -- Дата: 60% — завтра, 40% — послезавтра
      v_stdate := TRUNC(SYSDATE) + CASE WHEN MOD(v_st_counter, 5) = 0 THEN 2 ELSE 1 END;

      v_st_num := 'ДЦСТ-'
               || CASE v_ware_id WHEN 9201 THEN 'П' WHEN 9202 THEN 'Е' ELSE 'Т' END
               || LPAD(v_st_counter, 5, '0');

      -- 3–5 паллет на СТ (чередование по остатку от деления)
      v_pall_cnt := 3 + MOD(v_st_counter + st_idx, 3);

      FOR pl_idx IN 1..v_pall_cnt LOOP
        v_pl_counter := v_pl_counter + 1;
        v_pall_uid   := 'ДЦПЛ' || LPAD(v_pl_counter, 7, '0');

        -- Вставка паллеты
        INSERT INTO RRL_SBORKA_PALLETS (
          ST_NUMBER, ADDR, WARE_ID, PALLET_UID,
          STDATE, TRANSTASK_ID, CONDITION,
          ORD, ZONE, LOAD_TYPE, NAPR
        ) VALUES (
          v_st_num, v_addr_str, v_ware_id, v_pall_uid,
          v_stdate, NULL, 0,
          i,        -- ORD = порядок по умолчанию из RRL_ADDR
          CASE MOD(v_ware_id, 3)
            WHEN 0 THEN 'ЗОНА-А'
            WHEN 1 THEN 'ЗОНА-Б'
            ELSE        'ЗОНА-В'
          END,
          CASE MOD(pl_idx, 2) WHEN 0 THEN 'П' ELSE 'Г' END,  -- тип борта
          v_raion
        );

        -- 8–12 строк на паллету
        v_row_cnt := 8 + MOD(v_pl_counter, 5);

        FOR rw_idx IN 1..v_row_cnt LOOP
          v_global_row := v_global_row + 1;

          -- Артикул: равномерно из 10 категорий
          v_art_cat    := MOD(v_global_row - 1, 10);
          v_art_num    := MOD(TRUNC((v_global_row - 1) / 10), 100) + 1;
          v_art_prefix := CASE v_art_cat
                            WHEN 0 THEN 'МОЛ' WHEN 1 THEN 'МЯС'
                            WHEN 2 THEN 'РЫБ' WHEN 3 THEN 'БАК'
                            WHEN 4 THEN 'КНС' WHEN 5 THEN 'ХЛБ'
                            WHEN 6 THEN 'НАП' WHEN 7 THEN 'КОД'
                            WHEN 8 THEN 'ЗАМ' ELSE    'ХИМ'
                          END;
          v_acticul := 'ДЦ-' || v_art_prefix || '-' || LPAD(v_art_num, 4, '0');

          -- Вес: 8–22 кг на строку
          v_weight   := 8  + MOD(v_global_row * 7, 15);
          -- Упаковки: 6–18 шт на строку
          v_pack_cnt := 6  + MOD(v_global_row * 3, 13);
          -- Объём упаковки: ~3–6 млн мм³ (ок. 0.5–1 л на штуку)
          v_taresize := 3000000 + MOD(v_global_row * 11, 3000001);

          INSERT INTO RRL_SBORKA_PALLET_ROWS (
            PALLET_UID,
            ARTICUL,
            ORDER_WEIGHT,
            TARESIZE,
            PACK_COUNT
          ) VALUES (
            v_pall_uid,
            v_acticul,
            v_weight,
            v_taresize,
            v_pack_cnt
          );
        END LOOP; -- строки
      END LOOP; -- паллеты
    END LOOP; -- СТ
  END LOOP; -- адреса

  COMMIT;

  DBMS_OUTPUT.PUT_LINE('047 done:');
  DBMS_OUTPUT.PUT_LINE('  Адресов:  ' || v_addrs.COUNT);
  DBMS_OUTPUT.PUT_LINE('  ТС:       ' || v_vehs.COUNT);
  DBMS_OUTPUT.PUT_LINE('  Водителей:' || v_drvs.COUNT);
  DBMS_OUTPUT.PUT_LINE('  СТ:       ' || v_st_counter);
  DBMS_OUTPUT.PUT_LINE('  Паллет:   ' || v_pl_counter);
  DBMS_OUTPUT.PUT_LINE('  Строк:    ' || v_global_row);
END;
