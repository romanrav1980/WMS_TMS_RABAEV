"""Generate the public offline store-help snapshot from the curated wiki source list."""
import hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def main():
 rows=[row for row in json.loads((ROOT/'docs/help/wiki-sources.json').read_text(encoding='utf-8'))if row['article_id'].startswith('store-receiving-')or row['article_id']=='store-scale-gateway']
 ids=[row['article_id']for row in rows];articles=[]
 for row in rows:
  path=(ROOT/row['path']).resolve()
  if not path.is_relative_to(ROOT/'wiki'):raise ValueError('Only curated wiki sources')
  raw=path.read_bytes();text=raw.decode('utf-8-sig');body=text.split('## '+row['section'],1)[1].split('\n## ',1)[0].strip()
  articles.append(dict(article_id=row['article_id'],title=row['title'],summary=row['summary'],body=body,related=[other for other in ids if other!=row['article_id']],source_revision=hashlib.sha256(raw).hexdigest()))
 interface='export interface HelpArticle { article_id: string; title: string; summary: string; body: string; related: string[]; source_revision?: string }\n'
 output='// Generated by scripts/store_help_bundle.py from curated wiki; online publication remains authoritative.\n'+interface+'export const helpArticles: HelpArticle[] = '+json.dumps(articles,ensure_ascii=False,indent=1)+';\nexport function findHelpArticle(articleId: string): HelpArticle | undefined { return helpArticles.find(article => article.article_id === articleId); }\n'
 (ROOT/'terminal/wms_terminal_web/src/features/delivery/help/helpArticles.ts').write_text(output,encoding='utf-8')
 print('Generated offline store help: '+str(len(articles))+' articles')
if __name__=='__main__':main()
