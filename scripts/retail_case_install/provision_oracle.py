"""Provision only an empty RABAEV for the local Retail Case installer."""
import argparse
import json
import os
import re
from pathlib import Path

import oracledb


GRANTS = (
    'CREATE SESSION', 'CREATE TABLE', 'CREATE SEQUENCE', 'CREATE VIEW',
    'CREATE PROCEDURE', 'CREATE TRIGGER', 'CREATE TYPE', 'CREATE SYNONYM',
)
SYS_GRANTS = (
    ('EXECUTE', 'DBMS_LOCK'), ('EXECUTE', 'DBMS_FLASHBACK'),
    ('EXECUTE', 'DBMS_CRYPTO'), ('SELECT', 'V_$SESSION'),
    ('SELECT', 'V_$SQL'), ('SELECT', 'V_$SQLAREA'),
)


def check_empty_schema(cursor):
    cursor.execute("select count(*) from dba_objects where owner='RABAEV'")
    if cursor.fetchone()[0]:
        raise RuntimeError('RABAEV is not empty. Existing objects will not be changed.')


def provision(connection, password, create_service=False):
    # Password is generated by the installer. Never accept SQL syntax here.
    if not re.fullmatch(r'[A-Za-z][A-Za-z0-9]{23,39}', password):
        raise ValueError('Database password must be a generated alphanumeric secret')
    q = connection.cursor()
    q.execute("select sys_context('USERENV','CON_NAME'),sys_context('USERENV','SERVICE_NAME') from dual")
    container, service = q.fetchone()
    if container == 'CDB$ROOT':
        raise RuntimeError('Connect to a PDB, not CDB$ROOT')
    if create_service and container.upper() != 'XEPDB1':
        raise RuntimeError('Automatic service provisioning is restricted to the new XEPDB1')
    if not create_service and service.lower() != 'orcl':
        raise RuntimeError('Existing database mode requires service orcl')
    # This check precedes GRANT, CREATE SERVICE, CREATE USER and triggers.
    check_empty_schema(q)
    q.execute("select count(*) from dba_users where username='RABAEV'")
    if q.fetchone()[0]:
        raise RuntimeError('RABAEV already exists. Provisioning refuses to change its password; use the manual install guide.')
    if create_service:
        q.execute("select count(*) from dba_services where lower(name)='orcl'")
        if q.fetchone()[0]:
            raise RuntimeError('Service orcl already exists; automatic provisioning refuses to replace it')
        import sys
        root = Path(__file__).resolve().parents[2]
        sys.path.insert(0, str(root/'scripts'))
        from install_oracle_release import statements
        for sql in statements(root/'db/clean_install/structure/40_local_xe_service.sql'):
            q.execute(sql)
    q.execute('CREATE USER RABAEV IDENTIFIED BY "'+password+'" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA UNLIMITED ON USERS')
    q.execute('GRANT '+', '.join(GRANTS)+' TO RABAEV')
    for privilege, name in SYS_GRANTS:
        q.execute('GRANT '+privilege+' ON SYS.'+name+' TO RABAEV')
    print(json.dumps({'schema':'RABAEV','container':container,'service':'orcl','created':True}))


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--create-xe-service', action='store_true')
    a = p.parse_args()
    with oracledb.connect(user='SYS', password=os.environ['RETAIL_ORACLE_SYS_PASSWORD'],
                          dsn=os.environ['RETAIL_ORACLE_ADMIN_DSN'], mode=oracledb.SYSDBA) as c:
        c.call_timeout = 120000
        provision(c, os.environ['WMS_ORACLE_PASSWORD'], a.create_xe_service)
    if a.create_xe_service:
        root_dsn = os.environ['RETAIL_ORACLE_ADMIN_DSN'].rsplit('/',1)[0]+'/XE'
        with oracledb.connect(user='SYS', password=os.environ['RETAIL_ORACLE_SYS_PASSWORD'],
                             dsn=root_dsn, mode=oracledb.SYSDBA) as c:
            q = c.cursor()
            q.execute('ALTER PLUGGABLE DATABASE XEPDB1 SAVE STATE')
            q.execute('ALTER SYSTEM REGISTER')


if __name__ == '__main__':
    main()
