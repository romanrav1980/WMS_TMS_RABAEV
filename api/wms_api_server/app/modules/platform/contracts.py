"""Public contracts for scoped access and published user knowledge."""
from dataclasses import dataclass
from typing import Protocol, Any
from .domain.access_assignments import AccessScope, RoleAssignment

@dataclass(frozen=True)
class KnowledgeArticle:
    article_id: str
    title: str
    summary: str
    body: str
    related: tuple[str, ...]
    sources: tuple[str, ...]
    revision: str
    required_permissions: frozenset[str] = frozenset()

class KnowledgeReader(Protocol):
    def articles(self) -> tuple[KnowledgeArticle, ...]: ...

__all__ = ["AccessScope", "RoleAssignment", "KnowledgeArticle", "KnowledgeReader"]

class AccessMetadataPort(Protocol):
    def workspaces(self, actor: str) -> dict[str,Any]: ...
    def navigation(self, actor: str) -> dict[str,Any]: ...
    def me(self, actor: str, legacy_group: str) -> dict[str,Any]: ...
    def catalog(self, actor: str) -> dict[str,Any]: ...
    def groups(self, actor: str, query: str, limit: int) -> list[dict[str,Any]]: ...
    def group(self, actor: str, group_id: str) -> dict[str,Any]: ...
    def preview_group(self, actor: str, payload: dict[str,Any]) -> dict[str,Any]: ...
    def objects(self, actor: str, kind: str, query: str, limit: int) -> list[dict[str,Any]]: ...
    def assignments(self, actor: str, username: str | None, limit: int) -> list[dict[str,Any]]: ...
    def explain(self, actor: str, target: str, permission: str, kind: str, object_id: str | None) -> dict[str,Any]: ...
    def command(self, actor: str, command: dict[str,Any]) -> dict[str,Any]: ...
    def receipt(self, actor: str, operation_id: str) -> dict[str,Any]: ...
class KnowledgeMetadataPort(Protocol):
    def spaces(self, actor: str) -> list[dict[str,Any]]: ...
    def articles(self, actor: str, space_id: str | None, query: str, status: str | None, limit: int) -> list[dict[str,Any]]: ...
    def article(self, actor: str, article_id: str) -> dict[str,Any]: ...
    def history(self, actor: str, article_id: str, limit: int) -> list[dict[str,Any]]: ...
    def command(self, actor: str, command: dict[str,Any]) -> dict[str,Any]: ...
    def receipt(self, actor: str, operation_id: str) -> dict[str,Any]: ...

class KnowledgePublicationPort(Protocol):
    def sources(self, actor: str) -> list[dict[str,Any]]: ...
    def preview(self, actor: str, source_id: str) -> dict[str,Any]: ...
    def import_draft(self, actor: str, request: dict[str,Any]) -> dict[str,Any]: ...
