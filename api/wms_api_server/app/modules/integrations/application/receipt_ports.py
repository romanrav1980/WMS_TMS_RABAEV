from typing import Protocol
from datetime import date


class SupplyPort(Protocol):
    def receive(self, raw: bytes, actor: str) -> dict: ...
    def list(self, warehouse_id: int | None, limit: int, actor: str, date_from: date|None=None, date_to: date|None=None, date_basis: str="PLANNED_ACCEPT", include_unplanned: bool=False) -> list[dict]: ...
    def get(self, order_id: str, actor: str) -> dict: ...
    def pallet_plan(self, order_id: str, body: dict, actor: str) -> dict: ...
    def by_receipt_document(self, document_id: int, actor: str) -> dict: ...

    def receipt_history(self, order_id: str, limit: int, after: str | None, actor: str) -> dict: ...


class AcknowledgementPort(Protocol):
    def receive(self, raw: bytes, actor: str) -> dict: ...
    def list_events(self, limit: int) -> list[dict]: ...
    def retry(self, event_id: str) -> dict: ...
