"""Equipment gateway ports; receipt/stock commands remain owned by delivery."""
from dataclasses import dataclass
from typing import Any, Iterator, Protocol


@dataclass(frozen=True)
class ScaleDelivery:
    key: str
    body: bytes
    lease_token: str
    attempts: int


class ScaleTransport(Protocol):
    def post_capture(self, body: bytes) -> bytes:
        """POST exact UTF-8 bytes; raise on timeout, invalid or non-success response."""
        ...


class ScaleOutbox(Protocol):
    def pending_count(self) -> int: ...
    def suspended_count(self) -> int: ...
    def pending_count(self) -> int: ...
    def suspended_count(self) -> int: ...
    def bodies(self) -> Iterator[bytes]: ...
    def entries(self, after_rowid: int) -> Iterator[tuple[int, bytes]]: ...
    def stage(self, body: bytes) -> str: ...
    def has_capture(self, device_id: str, capture_id: str) -> bool: ...
    def claim(self, now: float, lease_seconds: int) -> ScaleDelivery | None: ...
    def acknowledge(self, delivery: ScaleDelivery, response: bytes) -> None: ...
    def defer(self, delivery: ScaleDelivery, retry_at: float, error: str) -> None: ...
    def suspend(self, delivery: ScaleDelivery, error: str) -> None: ...


class ScaleGatewayApi(Protocol):
    def requests(self, device_id: str) -> list[dict[str, Any]]: ...
    def post_capture(self, body: bytes) -> bytes: ...


class ScaleMeasurement(Protocol):
    def observe_idle(self) -> None: ...
    def capture(self, request: dict[str, Any]) -> bytes: ...


class ScaleGatewayError(Exception):
    def __init__(self, code: str, retryable: bool = False) -> None:
        self.code = code
        self.retryable = retryable
        super().__init__(code)


