from typing import Protocol


class StoreOrderConflict(ValueError):
    pass


class StoreOrdersPort(Protocol):
    def receive(self, raw: bytes, actor: str) -> dict: ...
    def list(self, warehouse: int | None, limit: int, actor: str) -> list[dict]: ...
    def get(self, order_id: int, actor: str) -> dict: ...
    def configure(self, warehouse: int, store_code: str, body: dict, actor: str) -> dict: ...
    def calendar_context(self, warehouse: int, store_code: str, day: str, actor: str) -> dict: ...
    def set_calendar_exception(self, operation: str, body: dict, actor: str) -> dict: ...


class PreparationPort(Protocol):
    def auto_preview(self, order_id: int, limits: dict, actor: str) -> dict: ...
    def auto_prepare(self, order_id: int, payload: dict, actor: str) -> dict: ...
    def auto_resolve(self, order_id: int, payload: dict, actor: str) -> dict: ...
    def resolve(self,order_id: int,payload: dict,actor: str) -> dict: ...
    def layout(self,order_id: int,counts: dict[str,int],actor: str) -> dict: ...
    def readiness(self, order_id: int, actor: str) -> dict: ...
    def prepare(self, order_id: int, payload: dict, actor: str) -> dict: ...
