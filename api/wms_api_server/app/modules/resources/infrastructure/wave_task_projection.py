"""Projection of one physical full-pallet task for compatible logical wave owners."""
INSERT_TASKS = """
 insert into RRL_WAREHOUSE_TASK(
  TASK_ID,TASK_TYPE,TASK_SOURCE,SOURCE_TASK_ID,SOURCE_DOC_TYPE,SOURCE_DOC_ID,
  TARGET_ARTICUL,UID_PALLET,FROM_CELL,TO_CELL,FROM_WARE_ID,TO_WARE_ID,
  QTY,UNIT_CODE,QTY_MODE,PRIORITY,STATUS,CREATED_AT,CREATED_BY,PLANNED_FINISH_AT)
 with candidates as (
  select 'REPLENISHMENT' TASK_TYPE,'WAVE' TASK_SOURCE,
   rt.PICK_WAVE_REPLENISH_TASK_ID SOURCE_TASK_ID,'PICK_WAVE' SOURCE_DOC_TYPE,
   rt.PICK_WAVE_ID SOURCE_DOC_ID,rt.ARTICUL TARGET_ARTICUL,rt.PALLET_UID UID_PALLET,
   rt.SOURCE_CELL_CODE FROM_CELL,rt.TARGET_CELL_CODE TO_CELL,
   src.WARE_ID FROM_WARE_ID,dst.WARE_ID TO_WARE_ID,rt.QTY,sr.BASE_UOM UNIT_CODE,
   case rt.REPLENISHMENT_QTY_MODE when 'FULL_PALLET' then 'PALLET' else 'BASE' end QTY_MODE,
   case when sh.CASE_PICK_SHORT_ID is not null then 0 else 100 end PRIORITY,
   case rt.STATUS when 'RELEASED' then 'PLANNED' else rt.STATUS end STATUS,
   systimestamp CREATED_AT,:actor CREATED_BY,sh.RECOVERY_DEADLINE_AT PLANNED_FINISH_AT,
   row_number()over(
    partition by rt.REPLENISHMENT_QTY_MODE,
     case when rt.REPLENISHMENT_QTY_MODE='FULL_PALLET' then rt.PALLET_UID
          else to_char(rt.PICK_WAVE_REPLENISH_TASK_ID) end,
     rt.SOURCE_CELL_CODE,rt.TARGET_CELL_CODE,rt.QTY
    order by case when sh.CASE_PICK_SHORT_ID is not null then 0 else 100 end,
     rt.PICK_WAVE_REPLENISH_TASK_ID) PALLET_RANK
  from RRL_PICK_WAVE_REPLENISH_TASK rt
  join RRL_PICK_WAVE w on w.PICK_WAVE_ID=rt.PICK_WAVE_ID
  join RRL_STOCK_RESERVATION sr on sr.RESERVATION_ID=rt.SOURCE_RESERVATION_ID
  join RRL_CELLS src on src.CELL=rt.SOURCE_CELL_CODE
  join RRL_CELLS dst on dst.CELL=rt.TARGET_CELL_CODE
  join RRL_REMAINS rem on rem.UID_POLETA=rt.PALLET_UID and rem.CELL=rt.SOURCE_CELL_CODE
  left join RRL_CASE_PICK_SHORT sh on sh.REPLENISH_TASK_ID=rt.PICK_WAVE_REPLENISH_TASK_ID
   and sh.RECOVERY_STATE='WAIT_REPLENISHMENT'
  where rt.PICK_WAVE_ID=:wave and rt.STATUS in('RELEASED','ASSIGNED','IN_PROGRESS')
   and w.STATUS='LAUNCHED' and src.WARE_ID=w.WARE_ID and dst.WARE_ID=w.WARE_ID
   and sr.STATUS in('ACTIVE','ALLOCATED','PICKING') and sr.RESERVATION_KIND='HARD'
   and sr.BASE_QTY>0 and sr.ARTICUL=rt.ARTICUL
   and sr.UID_PALLET=rt.PALLET_UID and sr.CELL=rt.SOURCE_CELL_CODE
   and rt.SOURCE_CELL_CODE!=rt.TARGET_CELL_CODE
   and (nvl(rt.REPLENISHMENT_QTY_MODE,'BASE')!='FULL_PALLET' or
       (rt.QTY=rem.REMAIN and RRL_STOCK_REPL_SHARED.allowed(
        rt.PALLET_UID,rt.SOURCE_CELL_CODE,rt.TARGET_CELL_CODE,w.WARE_ID,sr.RESERVATION_ID)=1))
   and not exists(select 1 from RRL_WAREHOUSE_TASK wt where wt.TASK_SOURCE='WAVE'
    and wt.TASK_TYPE='REPLENISHMENT' and wt.SOURCE_TASK_ID=rt.PICK_WAVE_REPLENISH_TASK_ID)
   and (nvl(rt.REPLENISHMENT_QTY_MODE,'BASE')!='FULL_PALLET' or not exists(
    select 1 from RRL_WAREHOUSE_TASK wt where wt.UID_PALLET=rt.PALLET_UID
     and wt.FROM_CELL=rt.SOURCE_CELL_CODE and wt.STATUS not in('DONE','CANCELLED')))
 )
 select RRL_WAREHOUSE_TASK_SQ.nextval,b.TASK_TYPE,b.TASK_SOURCE,b.SOURCE_TASK_ID,
  b.SOURCE_DOC_TYPE,b.SOURCE_DOC_ID,b.TARGET_ARTICUL,b.UID_PALLET,b.FROM_CELL,b.TO_CELL,
  b.FROM_WARE_ID,b.TO_WARE_ID,b.QTY,b.UNIT_CODE,b.QTY_MODE,b.PRIORITY,b.STATUS,
  b.CREATED_AT,b.CREATED_BY,b.PLANNED_FINISH_AT
 from (select * from candidates where PALLET_RANK=1
  order by PRIORITY,SOURCE_TASK_ID fetch first 200 rows only)b
"""
