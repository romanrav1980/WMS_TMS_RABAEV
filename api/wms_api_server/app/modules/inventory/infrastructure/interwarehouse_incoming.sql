with candidates as(
 select OPERATION_ID from RRL_INTERWARE_PLAN where TARGET_TT_ID=:trip
 union select PLAN_OPERATION_ID from RRL_INTERWARE_DECISION where TARGET_TT_ID=:trip
)
select p.OPERATION_ID,p.SOURCE_WARE_ID,p.SOURCE_TT_ID,p.SOURCE_LOAD_OPERATION_ID,nvl(p.SOURCE_PLACE_UID,p.ROOT_UID)PALLET_IDENTIFIER,p.ROOT_UID STOCK_PALLET_IDENTIFIER,
 source_leaf.ARTICLE ARTICLE,
 source_leaf.QUANTITY QUANTITY,
 source_leaf.BASE_UOM BASE_UOM,
 case when r.OPERATION_ID is not null and(r.EXPECTED_BASE_QTY is null or r.BASE_QTY=r.EXPECTED_BASE_QTY)then 1 else 0 end RECEIPT_COMPLETE,
 RRL_STOCK_PLAN_HELPER.decimal_text(r.BASE_QTY)RECEIVED_QUANTITY,
 RRL_STOCK_PLAN_HELPER.decimal_text(case when r.EXPECTED_BASE_QTY is not null then r.EXPECTED_BASE_QTY-r.BASE_QTY else 0 end)SHORT_QUANTITY,
 case when r.OPERATION_ID is not null then nvl(p.SOURCE_PLACE_UID,r.ROOT_UID)end RECEIVED_PALLET_IDENTIFIER,r.ROOT_UID RECEIVED_STOCK_IDENTIFIER,
 loss.OPERATION_ID SHORTAGE_CONFIRMATION_OPERATION_ID,
 RRL_STOCK_PLAN_HELPER.decimal_text(nvl(loss.SHORT_QTY,0))CONFIRMED_SHORT_QUANTITY,
 case when confirmed.STATE='APPLIED'and confirmed.COMMAND_TYPE='INTERWARE_SHORTAGE_CONFIRM'and r.BASE_QTY+loss.SHORT_QTY=r.EXPECTED_BASE_QTY then 1 else 0 end SHORTAGE_RESOLVED,
 RRL_STOCK_PLAN_HELPER.decimal_text(dispatch.BASE_QTY)LOADED_QUANTITY,l.ROOT_UID LOADED_PALLET_IDENTIFIER,
 u.OPERATION_ID UNLOAD_OPERATION_ID,r.OPERATION_ID RECEIPT_OPERATION_ID,
 placement.TASK_ID PLACED_TASK_ID,b.ST_ID ONWARD_ST_ID,b.ST_IDENTIFIER ONWARD_ST_IDENTIFIER,
 l.LOAD_OPERATION_ID,l.TT_ID LOAD_TRIP_ID,l.STATUS LOAD_STATUS,o.STATE LOAD_OPERATION_STATE,
 th.DECISION_KIND TEMPERATURE_DECISION,
 receipt_op.STATE RECEIPT_OPERATION_STATE,placement_op.STATE PLACEMENT_OPERATION_STATE,
 to_char(placement.CREATED_AT,'YYYY-MM-DD"T"HH24:MI:SS.FF6TZH:TZM') PLACED_AT,
 to_char(RRL_INTERWARE_ROUTING.ready_due(p.OPERATION_ID),'YYYY-MM-DD"T"HH24:MI:SS.FF6TZH:TZM') READY_DUE
from candidates candidate join RRL_INTERWARE_PLAN p on p.OPERATION_ID=candidate.OPERATION_ID
left join json_table(p.SOURCE_COMPOSITION_JSON,'$.nodes[*]'columns(
 UID_VALUE varchar2(200)path '$.uid',KIND_VALUE varchar2(20)path '$.kind',
 ARTICLE varchar2(160)path '$.article',QUANTITY varchar2(60)path '$.quantity',BASE_UOM varchar2(20)path '$.base_uom'))source_leaf
 on source_leaf.UID_VALUE=p.ROOT_UID and source_leaf.KIND_VALUE='STOCK'
left join RRL_INTERWARE_UNLOAD u on u.PLAN_OPERATION_ID=p.OPERATION_ID
left join RRL_INTERWARE_RECEIPT r on r.PLAN_OPERATION_ID=p.OPERATION_ID
left join RRL_INTERWARE_SHORTAGE_FACT loss on loss.RECEIPT_OPERATION_ID=r.OPERATION_ID
left join RRL_STOCK_OPERATION confirmed on confirmed.OPERATION_ID=loss.OPERATION_ID
left join RRL_INTERWARE_PLACEMENT placement on placement.RECEIPT_OPERATION_ID=r.OPERATION_ID
left join RRL_STOCK_OPERATION receipt_op on receipt_op.OPERATION_ID=r.OPERATION_ID
left join RRL_STOCK_OPERATION placement_op on placement_op.OPERATION_ID=placement.OPERATION_ID
left join RRL_INTERWARE_ONWARD_BIND b on b.RECEIPT_OPERATION_ID=r.OPERATION_ID
left join RRL_TT_HU_LOAD_ST member_record on member_record.SBORKA_PALLET_ID=b.ST_ID and member_record.ACTIVE_FLAG=1
left join RRL_TT_HU_LOAD_FACT l on l.LOAD_OPERATION_ID=member_record.LOAD_OPERATION_ID
left join RRL_INTERWARE_ONWARD_DISPATCH dispatch on dispatch.OPERATION_ID=l.LOAD_OPERATION_ID
 and dispatch.BIND_OPERATION_ID=b.OPERATION_ID and dispatch.RECEIPT_OPERATION_ID=r.OPERATION_ID and dispatch.ROOT_UID=r.ROOT_UID
left join RRL_STOCK_OPERATION o on o.OPERATION_ID=l.LOAD_OPERATION_ID
left join RRL_INTERWARE_THERMAL_FACT th on th.PLAN_OPERATION_ID=p.OPERATION_ID and th.REVISION_NO=(select max(z.REVISION_NO)from RRL_INTERWARE_THERMAL_FACT z where z.PLAN_OPERATION_ID=p.OPERATION_ID)
where RRL_INTERWARE_ROUTING.target_trip(p.OPERATION_ID)=:trip
order by p.OPERATION_ID fetch first 201 rows only
