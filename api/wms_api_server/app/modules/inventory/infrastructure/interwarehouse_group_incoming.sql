select p.OPERATION_ID,p.SOURCE_WARE_ID,p.SOURCE_TT_ID,p.SOURCE_LOAD_OPERATION_ID,p.ROOT_UID PALLET_IDENTIFIER,
source.UID_VALUE STOCK_PALLET_IDENTIFIER,source.ARTICLE_VALUE ARTICLE,source.QTY_TEXT QUANTITY,source.UOM_TEXT BASE_UOM,
case when receipt.OPERATION_ID is not null then 1 else 0 end RECEIPT_COMPLETE,
RRL_STOCK_PLAN_HELPER.decimal_text(received.BASE_QTY)RECEIVED_QUANTITY,
'0' SHORT_QUANTITY,case when receipt.OPERATION_ID is not null then p.ROOT_UID end RECEIVED_PALLET_IDENTIFIER,
source.UID_VALUE RECEIVED_STOCK_IDENTIFIER,
cast(null as varchar2(100))SHORTAGE_CONFIRMATION_OPERATION_ID,'0' CONFIRMED_SHORT_QUANTITY,0 SHORTAGE_RESOLVED,
RRL_STOCK_PLAN_HELPER.decimal_text(dispatched.BASE_QTY)LOADED_QUANTITY,
case when dispatched.OPERATION_ID is not null then p.ROOT_UID end LOADED_PALLET_IDENTIFIER,
unloaded.OPERATION_ID UNLOAD_OPERATION_ID,receipt.OPERATION_ID RECEIPT_OPERATION_ID,
placed.TASK_ID PLACED_TASK_ID,bind.ST_ID ONWARD_ST_ID,bind.ST_IDENTIFIER ONWARD_ST_IDENTIFIER,
loaded.LOAD_OPERATION_ID,loaded.TT_ID LOAD_TRIP_ID,loaded.STATUS LOAD_STATUS,posted.STATE LOAD_OPERATION_STATE,
'NONE' TEMPERATURE_DECISION,'GROUP' SOURCE_KIND,
receipt_post.STATE RECEIPT_OPERATION_STATE,placed_post.STATE PLACEMENT_OPERATION_STATE
from RRL_IW_GROUP_PLAN p cross join
json_table(p.SOURCE_JSON,'$.lots[*]'columns(UID_VALUE varchar2(200)path '$.uid',ARTICLE_VALUE varchar2(160)path '$.article',QTY_TEXT varchar2(60)path '$.quantity',UOM_TEXT varchar2(20)path '$.base_uom'))source
left join RRL_IW_GROUP_UNLOAD unloaded on unloaded.PLAN_OPERATION_ID=p.OPERATION_ID
left join RRL_IW_GROUP_RECEIPT receipt on receipt.PLAN_OPERATION_ID=p.OPERATION_ID
left join RRL_IW_GROUP_RECEIPT_LINE received on received.OPERATION_ID=receipt.OPERATION_ID and received.ROOT_UID=source.UID_VALUE
left join RRL_IW_GROUP_PLACEMENT placed on placed.RECEIPT_OPERATION_ID=receipt.OPERATION_ID
left join RRL_IW_GROUP_ST_BIND bind on bind.RECEIPT_OPERATION_ID=receipt.OPERATION_ID and bind.ROOT_UID=source.UID_VALUE
left join RRL_IW_GROUP_DISPATCH dispatched on dispatched.BIND_OPERATION_ID=bind.OPERATION_ID
left join RRL_TT_HU_LOAD_FACT loaded on loaded.LOAD_OPERATION_ID=dispatched.OPERATION_ID
left join RRL_STOCK_OPERATION posted on posted.OPERATION_ID=dispatched.OPERATION_ID
left join RRL_STOCK_OPERATION receipt_post on receipt_post.OPERATION_ID=receipt.OPERATION_ID
left join RRL_STOCK_OPERATION placed_post on placed_post.OPERATION_ID=placed.OPERATION_ID
where p.TARGET_TT_ID=:trip
order by p.OPERATION_ID,source.UID_VALUE fetch first 201 rows only
