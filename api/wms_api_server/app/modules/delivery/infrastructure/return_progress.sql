with chosen as(
 select a.OPERATION_ID,s.WARE_ID from json_table(:ids,'$[*]'columns(ID varchar2(100)path '$')) selected
 join RRL_STORE_RETURN_APPROVAL a on a.OPERATION_ID=selected.ID
 join RRL_STORE_RETURN_SAP s on s.APPROVAL_OPERATION_ID=a.OPERATION_ID
 join RUSERS u on u.ID=:actor and nvl(u.DELETED,0)=0 and RRL_HAS_WRIGHT(u.ID,'store_return_approve')=1
 where upper(trim(u.USER_GROUP))='GLOBAL_ADMIN' or u.WARE_ID=s.WARE_ID
), latest_plan as(
 select pp.*,row_number()over(partition by pp.RECEIPT_OPERATION_ID order by pp.TASK_ID desc) RN
 from RRL_STORE_RETURN_PUT_PLAN pp join RRL_STORE_RETURN_RECEIPT rr on rr.OPERATION_ID=pp.RECEIPT_OPERATION_ID
 join chosen ch on ch.OPERATION_ID=rr.APPROVAL_OPERATION_ID
)
select /* RETURN_PROGRESS1355 */ a.OPERATION_ID APPROVAL_OPERATION_ID,a.WARE_ID,
 t.OPERATION_ID TRANSPORT_OPERATION_ID,t.TT_ID,
 h.OPERATION_ID HANDOVER_OPERATION_ID,h.PALLET_IDENTIFIER,
 p.OPERATION_ID PICKUP_OPERATION_ID,
 r.OPERATION_ID WAREHOUSE_RECEIPT_OPERATION_ID,r.UID_PALLET,r.ARTICLE,r.BASE_UOM,
 RRL_STOCK_PLAN_HELPER.decimal_text(r.BASE_QTY) RECEIVED_QUANTITY,
 r.OBSERVED_BATCH,r.BATCH_SOURCE,to_char(r.EXPIRY_DATE,'YYYY-MM-DD')EXPIRY_DATE,r.RECEIVE_CELL,
 plan_record.TASK_ID,wt.STATUS TASK_STATUS,wt.TO_CELL PLANNED_TARGET_CELL,
 placed.OPERATION_ID PLACEMENT_OPERATION_ID,placed.TARGET_CELL,
 sup.ST_ID SUPPLIER_ST_ID,sup.ST_IDENTIFIER SUPPLIER_ST_IDENTIFIER,
 dispatch.OPERATION_ID SUPPLIER_DISPATCH_OPERATION_ID,
 disposal.OPERATION_ID DISPOSAL_OPERATION_ID,req.OPERATION_ID DISPOSAL_REQUEST_OPERATION_ID
from chosen a
left join RRL_STORE_RETURN_TRANSPORT t on t.APPROVAL_OPERATION_ID=a.OPERATION_ID
left join RRL_STORE_RETURN_HANDOVER h on h.TRANSPORT_OPERATION_ID=t.OPERATION_ID
left join RRL_STORE_RETURN_PICKUP p on p.HANDOVER_OPERATION_ID=h.OPERATION_ID
left join RRL_STORE_RETURN_RECEIPT r on r.APPROVAL_OPERATION_ID=a.OPERATION_ID
left join latest_plan plan_record on plan_record.RECEIPT_OPERATION_ID=r.OPERATION_ID
 and plan_record.RN=1
left join RRL_WAREHOUSE_TASK wt on wt.TASK_ID=plan_record.TASK_ID
left join RRL_STORE_RETURN_PLACEMENT placed on placed.RECEIPT_OPERATION_ID=r.OPERATION_ID
left join RRL_STORE_RETURN_SUP_BIND sup on sup.RECEIPT_OPERATION_ID=r.OPERATION_ID
left join RRL_STORE_RETURN_SUP_DISPATCH dispatch on dispatch.BIND_OPERATION_ID=sup.OPERATION_ID
left join RRL_RETURN_DISPOSAL_REQUEST req on req.RECEIPT_OPERATION_ID=r.OPERATION_ID
left join RRL_RETURN_DISPOSAL_FACT disposal on disposal.RECEIPT_OPERATION_ID=r.OPERATION_ID
